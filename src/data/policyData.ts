export type PolicyAction = 'allow' | 'alert' | 'soft_block' | 'hard_block' | 'mask';
export type PolicyStatus = 'active' | 'inactive' | 'draft';
export type ProtectionLevel = 'low' | 'medium' | 'high' | 'critical';

export interface PolicyCondition {
  field: string;
  operator: 'equals' | 'contains' | 'matches' | 'in';
  value: string;
}

export interface Policy {
  id: string;
  name: string;
  description: string;
  status: PolicyStatus;
  dataTypes: string[];
  protectionLevel: ProtectionLevel;
  action: PolicyAction;
  userGroups: string[];
  aiPlatforms: string[];
  aiModels: string[];
  customPatterns: string[];
  conditions: PolicyCondition[];
  createdBy: string;
  createdAt: string;
  updatedAt: string;
  violations: number;
  lastTriggered: string;
  priority: number;
  category: string;
}

